"""Workflowy Mutation Coherence foundation (S01).

Dependency-light, versioned, fail-closed coherence contracts and
primitives: account-scoped paths and mutexing, strict on-disk schemas,
durable manifest/journal publication, one canonical cache-node codec, pure
field-authority reducers, the immutable-view/copy-on-write contract, and a
reusable multi-process fault harness.

S01 establishes contracts and primitives ONLY.  It does not migrate
production cache consumers, publish full-refresh epochs, enforce dirty
barriers, acquire mutation leases, or wire CRUD mutations into journaling.

Importing this package must not instantiate ``ServerConfig``, require
credentials, start FastMCP, connect to the broker, or create files.

Only the stable primitives later sessions need are exported here; internal
parsing helpers remain private to their modules.
"""

