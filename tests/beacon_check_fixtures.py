"""Fixture files for the beacon check engine (U01 §9.2) and the shared-seam
baseline (U01 §9.1, route (b)).

Every fixture is ``name -> (file name, text)``; the file name's extension
picks the language. The texts are built from lists of quoted lines so this
module itself contains no beacon comment block (Cartographer and the
hygiene would otherwise read them). ``beacon_seams_baseline.json`` holds the
base code's parser output for every text fixture here, so a fixture's text
may only change together with a regenerated baseline
(``tests/beacon_seams_baseline_gen.py``).
"""
from __future__ import annotations


def _text(*lines: str) -> str:
    return "\n".join(lines) + "\n"


